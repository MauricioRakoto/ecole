    <h1>📘 Manuel d'utilisation de notre application</h1>
    
    <section class="etape">
        <h3>1ère étape : Création d'une classe</h3>
        <ul>
            <li>Cliquez sur le menu <strong>classes</strong>.</li>
            <li>Sélectionnez <strong>Nouveau</strong>.</li>
            <li>Remplissez le formulaire avec :
                <ul>
                    <li>Nom de la classe</li>
                    <li>Niveau (ex. : 6ème, Terminale…)</li>
                    <li>Année début</li>
                    <li>Année fin</li>
                </ul>
            </li>
            <li>Cliquez sur <strong>Enregistrer</strong> pour valider.</li>
        </ul>
        <p class="argument">Cette étape permet de structurer votre établissement dans l'application. Sans création de classes, vous ne pourrez pas inscrire correctement les élèves ni organiser les matières.</p>
    </section>

    <section class="etape">
        <h3>2ème étape : Inscription d'un élève</h3>
        <ul>
            <li>Accédez au menu <strong>Inscription</strong>.</li>
            <li>Remplissez les informations demandées :
                <ul>
                    <li>Nom et prénom</li>
                    <li>Date de naissance</li>
                    <li>Sexe</li>
                    <li>Numéro matricule</li>
                    <li>Classe</li>
                </ul>
            </li>
            <li>Cliquez sur <strong>Enregistrer</strong> pour valider l'inscription.</li>
        </ul>
        <p class="argument">L’inscription est essentielle pour associer un élève à sa classe et garder un suivi précis de ses données scolaires tout au long de l’année.</p>
    </section>

    <section class="etape">
        <h3>3ème étape : Création d'une matière</h3>
        <ul>
            <li>Cliquez sur le menu <strong>Matières</strong>.</li>
            <li>Sélectionnez <strong>Nouveau</strong>.</li>
            <li>Remplissez le formulaire avec :
                <ul>
                    <li>Nom de la matière</li>
                    <li>Coefficient</li>
                </ul>
            </li>
            <li>Cliquez sur <strong>Enregistrer</strong> pour valider.</li>
        </ul>
        <p class="argument">Créer des matières avec leur coefficient permet de préparer les bulletins scolaires et d'organiser les cours selon le programme de l'établissement.</p>
    </section>

    <section class="etape">
        <h3>4ème étape : Voir la liste des élèves</h3>
        <ul>
            <li>Cliquez sur le menu <strong>classes</strong>.</li>
            <li>Cliquez sur le nom d'une classe.</li>
        </ul>
        <p class="argument">Consulter la liste des élèves permet de vérifier rapidement les inscriptions, de repérer les absences éventuelles et de mieux gérer le suivi scolaire.</p>
    </section>

    <section class="etape">
        <h3>5ème étape : Impression de la liste des élèves</h3>
        <ul>
            <li>Cliquez sur le menu <strong>classes</strong>.</li>
            <li>Cliquez sur le nom d'une classe.</li>
            <li>Vous arrivez sur la liste des élèves par le menu élève.</li>
            <li>Cliquez sur le bouton <strong>Imprimer</strong>.</li>
        </ul>
        <p class="argument">L’impression est utile pour disposer d’une version papier lors des réunions, inspections ou affichages administratifs.</p>
    </section>

    <section class="etape">
        <h3>6ème étape : Gestion des absences</h3>
        <ul>
            <li>Cliquez sur le menu <strong>classes</strong>.</li>
            <li>Cliquez sur le nom d'une classe.</li>
            <li>Cliquez sur le menu <strong>Absence</strong>.</li>
        </ul>
        <p class="argument">Le suivi des absences est primordial pour la discipline et le suivi pédagogique des élèves. Il permet aussi de générer des rapports pour les parents et l’administration.</p>
    </section>
